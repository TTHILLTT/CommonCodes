#include <bits/stdc++.h>
#define endl '\n'
using namespace std;
typedef long long LL;
inline LL read() {
    LL s = 0, w = 1;
    char ch = getchar();
    while (ch < '0' || ch > '9') {
//      if(ch=='-')w=-1;
        ch = getchar();
    }
    while (ch >= '0' && ch <= '9') {
        s = s * 10 + ch - '0', ch = getchar();
    }
    return s * w;
}
LL n, p[500005], bit[500005], res[500005];
LL lowbit(LL x) {
    return x & -x;
}
void update(LL x) {
    while (x <= n) {
        bit[x]--;
        x += lowbit(x);
    }
}
LL query(LL x) {
    LL ans = 0;
    while (x > 0) {
        ans += bit[x];
        x -= lowbit(x);
    }
    return ans;
}
LL ffind(LL k) {
    LL l = 1, r = n, ans = 1;
    while(l <= r) {
        LL mid = (l + r) >> 1;
        if (query(mid) >= k) {
            ans = mid;
            r = mid - 1;
        } else {
            l = mid + 1;
        }
    }
    return ans;
}
