#include <bits/stdc++.h>
using namespace std;
typedef long long LL;
const LL N = 100005;
LL n, tree[N], a[N], b[N];
LL lowbit(LL x) {
    return x & -x;
}
void add(LL x, LL val) {
    while (x <= n) {
        tree[x] += val;
        x += lowbit(x);
    }
}
LL kth(LL k) {
    LL idx = 0;
    LL bit = 1;
    while ((bit << 1) <= n) {
        bit <<= 1;
    }
    while (bit) {
        LL nxt = idx + bit;
        if (nxt <= n && tree[nxt] < k) {
            idx = nxt;
            k -= tree[nxt];
        }
        bit >>= 1;
    }
    return idx + 1;
}
int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout.tie(0);
    cin >> n;
    for (LL i = 1; i <= n; i++) {
        cin >> a[i];
        b[i] = a[i];
    }
    sort(b + 1, b + n + 1);
    LL m = unique(b + 1, b + n + 1) - (b + 1);
    for (LL i = 1; i <= n; i++) {
        LL x = a[i];
        LL id = lower_bound(b + 1, b + m + 1, x) - b;
        add(id, 1);
        if (i % 2 == 1) {
            LL pos = kth((i + 1) / 2);
            cout << b[pos] << endl;
        }
    }
    return 0;
}
