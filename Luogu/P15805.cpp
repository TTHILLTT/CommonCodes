#include <bits/stdc++.h>
using namespace std;

using LL = long long;

const LL INF = (LL)4e18;
const LL MOD = 1000000000LL;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n, m;
    cin >> n >> m;

    vector<vector<pair<int, int>>> adj(n + 1);
    for (int i = 0; i < m; ++i) {
        int u, v, w;
        cin >> u >> v >> w;
        adj[u].emplace_back(v, w);
        adj[v].emplace_back(u, w);
    }

    LL ans = 0;
    LL d[105][105];

    for (int l = 1; l <= n; ++l) {
        for (int i = 1; i <= n; ++i) {
            for (int j = 1; j <= n; ++j) {
                d[i][j] = INF;
            }
        }
        for (int i = 1; i <= n; ++i) d[i][i] = 0;

        for (int r = l; r <= n; ++r) {
            for (int i = l; i < r; ++i) {
                d[i][r] = INF;
                d[r][i] = INF;
                for (auto [v, w] : adj[r]) {
                    if (l <= v && v < r && d[i][v] + w < d[i][r]) {
                        d[i][r] = d[i][v] + w;
                    }
                }
                d[r][i] = d[i][r];
            }

            for (int i = l; i <= r; ++i) {
                for (int j = l; j <= r; ++j) {
                    if (d[i][r] + d[r][j] < d[i][j]) {
                        d[i][j] = d[i][r] + d[r][j];
                    }
                }
            }

            for (int i = l; i <= r; ++i) {
                for (int j = i; j <= r; ++j) {
                    ans += d[i][j];
                    if (ans >= MOD) ans %= MOD;
                }
            }
        }
    }

    cout << ans % MOD << '\n';
    return 0;
}
