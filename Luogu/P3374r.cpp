#include <bits/stdc++.h>
#define endl '\n'
using namespace std;
typedef long long LL;
inline LL read() {
    LL s = 0, w = 1;
    char ch = getchar();
    while (ch < '0' || ch > '9') {
//      if(ch=='-')w=-1;
        ch = getchar();
    }
    while (ch >= '0' && ch <= '9') {
        s = s * 10 + ch - '0', ch = getchar();
    }
    return s * w;
}
LL n, m;
LL a[500005], c[500005];
void add(LL x, LL k) {
    while (x <= n) {
        c[x] += k;
        x += -x & x;
    }
    return;
}
LL sum(LL x) {
    LL res = 0;
    while (x > 0) {
        res += c[x];
        x -= -x & x;
    }
    return res;
}
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    cout.tie(nullptr);
    // freopen(".in","r",stdin);
    // freopen(".out","w",stdout);
    cin >> n >> m;
    for (LL i = 1; i <= n; i++) {
        cin >> a[i];
        add(i, a[i]);
    }
    while (m--) {
        LL o;
        cin >> o;
        if (o == 1) {
            LL x, k;
            cin >> x >> k;
            add(x, k);
        } else {
            LL x, y;
            cin >> x >> y;
            cout << sum(y) - sum(x - 1) << endl;
        }
    }
    return 0;
}
